package basic;

public class TypeCasting {

	public static void main(String[] args) {
		
		// Implicit Typecasting
		
		int a = 10;
		double b = a;
		System.out.println(b);
		
		
		//Explicit Typecatsing
		
		short c = 4;
		byte d = (byte)c;
		
		System.out.println(c);
		
		char ch = 'a';
		int n = (int)ch; 
		System.out.println(n);

		
		
	
	

	}

}
